from app.llm_service import get_llm
from my_agents import acceptance_criteria_agent
from my_agents.requirement_agent import requirement_agent
from my_agents.acceptance_criteria_agent import generate_acceptance_criteria


def review_agent(
    user_story: str,
    requirement_agent: str,
    acceptance_criteria: str,
):
    llm = get_llm()
    prompt = f"""
You are an experienced Senior QA Engineer and
Independent Acceptance Criteria Reviewer.

Your responsibility is to review the acceptance criteria
generated by another AI agent.

Do not blindly trust the generated output.

ORIGINAL USER STORY:
{user_story}

REQUIREMENT ANALYSIS:
{requirement_agent}

GENERATED ACCEPTANCE CRITERIA:
{acceptance_criteria}


REVIEW RULES:

1. Treat the original user story as the primary source
   of truth.

2. Check whether each confirmed acceptance criterion
   is supported by the original user story.

3. Identify unsupported assumptions, implementation
   details, and invented business rules.

4. Check whether suggested QA scenarios are clearly
   separated from confirmed acceptance criteria.

5. Check whether important ambiguities are identified.

6. Check whether requirement coverage accurately maps
   to the original requirements.

7. Do not convert assumptions into confirmed requirements.

8. Do not invent new requirements during the review.

9. Do not approve an acceptance criterion merely because
   it appears in the Requirement Analyst output.

10. Explain why each issue needs correction.


OUTPUT FORMAT:

Section 1: Overall Review Status
- Approved / Needs Improvement
- Brief explanation.

Section 2: Valid Acceptance Criteria
- List criteria supported by the original user story.

Section 3: Unsupported Acceptance Criteria
- List criteria that introduce assumptions.
- Explain why each is unsupported.

Section 4: Missing Clarifications
- Identify important questions that need clarification
  from the Business Analyst or Product Owner.

Section 5: Requirement Coverage Review
- Check whether the generated coverage accurately
  represents the original requirements.
- Identify missing or incorrectly mapped requirements.

Section 6: Recommended Corrections
- Suggest how the acceptance criteria should be corrected.
- Do not invent missing business rules.

FINAL VALIDATION:
- Do not approve unsupported requirements.
- Do not treat implementation choices as confirmed rules.
- Ensure every valid criterion is traceable to the original
  user story.

Return exactly the six sections.
"""

    response = llm.invoke(prompt)

    return response.content
